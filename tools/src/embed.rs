//! `cargo xtask embed-assets`: regenerates `mod/src/defaults.rs` from `tools/defaults/`.
//!
//! A native package only accepts `.rs` and `.toml` files under `src/`, so the default files (rules,
//! functions, scripts, the agent guide, schemas) travel as Rust constants and the mod writes them
//! into `config/` when they are missing.
use std::process::ExitCode;

use crate::util::{files_below, raw_string, read, root, write, Result};

pub fn run() -> Result<ExitCode> {
    let root = root();
    let source = root.join("tools/defaults");
    let target = root.join("mod/src/defaults.rs");
    let files = files_below(&source, "")?;
    let mut lines = vec![
        "//! Generated by `cargo xtask embed-assets` from tools/defaults/. Do not edit by hand.".to_owned(),
        String::new(),
        "/// Files written into `config/tiktok_live/` when they are missing: (relative path, contents).".to_owned(),
        "pub const FILES: &[(&str, &str)] = &[".to_owned(),
    ];
    for path in &files {
        let relative = path.strip_prefix(&source).map_err(|e| e.to_string())?.to_string_lossy().replace('\\', "/");
        lines.push(format!("    (\"{relative}\", {}),", raw_string(&read(path)?)));
    }
    lines.push("];".to_owned());
    lines.push(String::new());
    lines.push("/// The interaction preset (`/tiktok preset install`).".to_owned());
    lines.push(format!("pub const INTERACTIONS: &str = {};", raw_string(&read(&source.join("events/interactions.yml"))?)));
    write(&target, &(lines.join("\n") + "\n"))?;
    println!("{} ({} files)", target.display(), files.len());
    Ok(ExitCode::SUCCESS)
}
